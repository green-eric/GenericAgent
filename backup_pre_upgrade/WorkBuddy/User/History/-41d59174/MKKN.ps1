$keepSet = New-Object System.Collections.Generic.HashSet[string]([StringComparer]::OrdinalIgnoreCase)
foreach ($k in $keepList) { [void]$keepSet.Add($k) }

$allSkills = Get-ChildItem $skillDir -Directory
$deleted = @()
$kept = @()
$failed = @()

foreach ($skill in $allSkills) {
    if ($keepSet.Contains($skill.Name)) {
        $kept += $skill.Name
    } else {
        try {
            Remove-Item $skill.FullName -Recurse -Force
            $deleted += $skill.Name
            Write-Output "DEL: $($skill.Name)"
        } catch {
            $failed += $skill.Name
            Write-Output "FAIL: $($skill.Name)"
        }
    }
}

Write-Output ""
Write-Output "=== RESULT ==="
Write-Output "Deleted: $($deleted.Count)"
Write-Output "Kept: $($kept.Count)"
Write-Output "Failed: $($failed.Count)"
Write-Output ""
Write-Output "=== KEPT LIST ==="
foreach ($k in ($kept | Sort-Object)) { Write-Output "  $k" }
