class FinancialReportParser:
    def __init__(self, raw: str):
        self.raw = raw
        self.segments = self._split(raw)
    def _split(self, text):
        parts = re.split(r'(\d{4}[-/年]?\d{1,2}[-/月]?\d{1,2}[日号]?)', text)
        combined, i = [], 0
        while i < len(parts)-1:
            ds, ct = parts[i], parts[i+1] if i+1 < len(parts) else ""
            if re.match(r'\d{4}', ds) and len(ds)>=8:
                n = self._norm(ds)
                if n: combined.append({"date":n,"content":ct})
            i += 2
        if len(combined)<2: combined = [{"date":None,"content":text}]
        for seg in combined: seg["type"] = self._classify(seg["content"])
        return combined
    @staticmethod
    def _norm(d): d=d.replace('年','').replace('月','').replace('日','').replace('/','').replace('-',''); return d if len(d)==8 and d.isdigit() else None
    def _classify(self,c):
        if re.search(r'年报|年度报告|全年',c): return "annual"
        if re.search(r'Q\d|单季|一季|二季|三季|四季|中报',c): return "quarterly"
        if re.search(r'半年报|中期报告',c): return "semi_annual"
        return "unknown"
    def latest(self, rtype):
        cand = [s for s in self.segments if s["type"]==rtype and s["date"]]
        if not cand: cand = [s for s in self.segments if self._classify(s["content"])==rtype]
        if not cand: return None
        cand.sort(key=lambda x: x["date"], reverse=True)
        return cand[0]
    def extract(self, seg):
        c = seg.get("content","")
        d = {}
        d["roe"] = extract_percent_flex(c, ["加权净资产收益率ROE","净资产收益率","ROE"])
        d["gross_margin"] = extract_percent_flex(c, ["销售毛利率","毛利率"])
        d["net_margin"] = extract_percent_flex(c, ["销售净利率","净利率"])
        d["revenue_yoy"] = extract_percent_flex(c, ["营业收入同比增长","营收同比增长"])
        d["profit_yoy"] = extract_percent_flex(c, ["净利润同比增长","归母净利润同比增长"])
        d["debt_ratio"] = extract_percent_flex(c, ["资产负债率","负债率"])
        rev = re.search(r'营业(?:总)?收入\s*([-+]?\d+\.?\d*)\s*(万[亿]?元|亿元|万元|万亿元|千元|元)', c)
        d["revenue"] = parse_number_with_unit(rev.group(0)) if rev else None
        np_ = re.search(r'净利润\s*([-+]?\d+\.?\d*)\s*(万[亿]?元|亿元|万元|万亿元|千元|元)', c)
        d["net_profit"] = parse_number_with_unit(np_.group(0)) if np_ else None
        dp = re.search(r'扣非净利润\s*([-+]?\d+\.?\d*)\s*(万[亿]?元|亿元|万元|万亿元|千元|元)', c)
        d["deducted_profit"] = parse_number_with_unit(dp.group(0)) if dp else None
        ocf = re.search(r'经营活动.*现金流量净额\s*([-+]?\d+\.?\d*)\s*(万[亿]?元|亿元|万元|万亿元|千元|元)', c)
        d["ocf_abs"] = parse_number_with_unit(ocf.group(0)) if ocf else None
        if d["net_profit"] and d["ocf_abs"] and d["net_profit"]!=0:
            d["ocf_to_profit"] = d["ocf_abs"]/d["net_profit"]
        else: d["ocf_to_profit"] = None
        d["asset_turnover"] = extract_number_flex(c, [r'总资产周转率\s*([\d.]+)\s*次'])
        d["ar_turnover"] = extract_number_flex(c, [r'应收账款周转率\s*([\d.]+)\s*次'])
        return d

def extract_number_flex(text, patterns):
    if not text: return None
    for p in patterns:
        m = re.search(p, text)
        if m:
            try: return float(m.group(1))
            except: continue
    return None

def parse_financial_all(content):
    parser = FinancialReportParser(content)
    res = {k:None for k in ["annual_roe","annual_gross_margin","annual_net_margin",
        "annual_revenue_yoy","annual_profit_yoy","annual_debt_ratio",
        "annual_net_profit","annual_deducted_profit","annual_revenue",
        "annual_ocf_to_profit","annual_ocf_abs","total_asset_turnover","ar_turnover",
        "latest_revenue_yoy","latest_profit_yoy",
        "annual_report_date", "latest_report_date"]}
    a = parser.latest("annual")
    if a:
        ad = parser.extract(a)
        for t,s in [("annual_roe","roe"),("annual_gross_margin","gross_margin"),
                    ("annual_net_margin","net_margin"),("annual_revenue_yoy","revenue_yoy"),
                    ("annual_profit_yoy","profit_yoy"),("annual_debt_ratio","debt_ratio"),
                    ("annual_net_profit","net_profit"),("annual_deducted_profit","deducted_profit"),
                    ("annual_revenue","revenue"),("annual_ocf_to_profit","ocf_to_profit"),
                    ("annual_ocf_abs","ocf_abs"),("total_asset_turnover","asset_turnover"),
                    ("ar_turnover","ar_turnover")]:
            res[t] = ad.get(s)
        res["annual_report_date"] = a["date"]
    q = parser.latest("quarterly") or parser.latest("semi_annual")
    if q:
        qd = parser.extract(q)
        res["latest_revenue_yoy"] = qd.get("revenue_yoy")
        res["latest_profit_yoy"] = qd.get("profit_yoy")
        res["latest_report_date"] = q["date"]
    if res["annual_roe"] is None:
        fb = parser.extract({"content":content})
        for k in ["roe","gross_margin","net_margin","revenue_yoy","profit_yoy","debt_ratio","net_profit"]:
            res["annual_"+k] = fb.get(k)
    return res

