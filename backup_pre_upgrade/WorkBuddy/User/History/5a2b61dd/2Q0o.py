def parse_number_with_unit(text: str) -> Optional[float]:
    m = re.search(r'([-+]?\d+\.?\d*)\s*(万[亿]?元|亿元|万元|万亿元|千元|元)', text)
    if not m: return None
    num, unit = float(m.group(1)), m.group(2)
    if '万亿' in unit: return num * 1e12
    if '亿' in unit: return num * 1e8
    if '万' in unit: return num * 1e4
    if '千' in unit: return num * 1e3
    return num

def extract_percent_flex(text, keywords):
    if not text: return None
    for kw in keywords:
        for pat in [re.escape(kw)+r'[：:= ]*([-+]?\d+\.?\d*)\s*%',
                    re.escape(kw)+r'[为是]*([-+]?\d+\.?\d*)\s*%',
                    r'([-+]?\d+\.?\d*)\s*%[，。；\s]*'+re.escape(kw)]:
            m = re.search(pat, text)
            if m:
                try: return float(m.group(1))
                except: continue
    m = re.findall(r'([-+]?\d+\.?\d*)\s*%', text)
    return float(m[-1]) if m else None

def extract_industry_from_content(content: str) -> Optional[str]:
    if not content: return None
    patterns = [
        r'所属一级行业[：:]\s*([^\s，,、；;]+)',
        r'申万.*?行业[：:]\s*([^\s，,、；;]+)',
        r'一级行业[为是]?\s*([^\s，,、；;]+)',
        r'行业分类[：:]\s*([^\s，,、；;]+)',
        r'(?:申万|SW)\s*([\u4e00-\u9fa5]+)行业',
        r'属于\s*([\u4e00-\u9fa5]+)行业',
        r'所处行业[为是]?([\u4e00-\u9fa5]+)',
        r'主营业务为([\u4e00-\u9fa5]+)',
    ]
    for pat in patterns:
        m = re.search(pat, content)
        if m:
            raw = m.group(1).strip()
            if 2<=len(raw)<=15: return standardize_industry(raw)
    sec_m = re.search(r'所属二级行业[：:]\s*([^\s，,、；;]+)', content)
    if sec_m:
        sec = sec_m.group(1).strip()
        return SECONDARY_TO_PRIMARY.get(sec)
    return None

