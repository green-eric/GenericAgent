def run_neodata(query: str) -> dict:
    cmd = [sys.executable, str(Config.QUERY_SCRIPT), "--query", query, "--data-type", "api"]
    for attempt in range(1, Config.API_RETRY_TIMES+2):
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=Config.API_TIMEOUT)
            out = res.stdout.strip()
            if "<Objs Version=" in out:
                m = re.search(r'\{[\s\S]*\}', out)
                if m: out = m.group()
            if not out:
                time.sleep(Config.API_RETRY_BACKOFF_BASE**attempt)
                continue
            data = json.loads(out)
            if data.get("code")=="200": return data
            time.sleep(Config.API_RETRY_BACKOFF_BASE)
        except subprocess.TimeoutExpired:
            time.sleep(Config.API_RETRY_BACKOFF_BASE*attempt)
        except (json.JSONDecodeError, Exception):
            time.sleep(Config.API_RETRY_BACKOFF_BASE)
    return {"code":"error","msg":"exhausted"}

