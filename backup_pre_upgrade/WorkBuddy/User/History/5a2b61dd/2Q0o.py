def generate_report(results, output_dir, error_list=None):
    import pandas as pd
    ts = datetime.now().strftime('%Y%m%d_%H%M%S')
    path = os.path.join(output_dir, f"股票业绩评价_{ts}.xlsx")
    rows = []
    for r in results:
        d = r.get("score_detail",{})
        base = "; ".join(f"{k}:{v}" for k,v in r.get("score_base",{}).items())
        rows.append({"股票代码":r.get("ts_code"),"股票名称":r.get("name"),"一级行业":r.get("industry_l1"),
                     "加权ROE(%)":r.get("annual_roe"),"毛利率(%)":r.get("annual_gross_margin"),
                     "净利率(%)":r.get("annual_net_margin"),"营收同比(%)":r.get("annual_revenue_yoy"),
                     "净利润同比(%)":r.get("annual_profit_yoy"),"经营现金流/净利润":r.get("annual_ocf_to_profit"),
                     "资产负债率(%)":r.get("annual_debt_ratio"),"盈利评分":d.get("score_profit"),
                     "成长评分":d.get("score_growth"),"现金流评分":d.get("score_ocf"),"偿债评分":d.get("score_debt"),
                     "总评分":r.get("total_score"),"评级":r.get("rating"),"评分基准":base,"数据完整度":r.get("completeness")})
    df = pd.DataFrame(rows)
    if df.empty: return ""
    df["评级"] = df["评级"].astype(pd.CategoricalDtype(categories=["A","B","C","D","E"], ordered=True))
    df.sort_values(["评级","总评分"], ascending=[True, False], inplace=True)
    with pd.ExcelWriter(path, engine='openpyxl') as w:
        df.to_excel(w, sheet_name='综合评价结果', index=False)
        for rate in ["A","B","C","D","E"]:
            sub = df[df["评级"]==rate]
            if not sub.empty: sub.to_excel(w, sheet_name=f'{rate}级股票', index=False)
        low = df[df["数据完整度"]=="低"]
        if not low.empty: low.to_excel(w, sheet_name='低完整度股票', index=False)
        if error_list:
            pd.DataFrame(error_list).to_excel(w, sheet_name='异常日志', index=False)
        stats = [{"项目":"股票总数","数值":len(df)},{"项目":"A级","数值":int((df["评级"]=="A").sum())},
                 {"项目":"B级","数值":int((df["评级"]=="B").sum())},{"项目":"C级","数值":int((df["评级"]=="C").sum())},
                 {"项目":"D级","数值":int((df["评级"]=="D").sum())},{"项目":"E级","数值":int((df["评级"]=="E").sum())},
                 {"项目":"平均评分","数值":round(df["总评分"].mean(),2)},{"项目":"最高评分","数值":round(df["总评分"].max(),2)},
                 {"项目":"完整-高","数值":int((df["数据完整度"]=="高").sum())},{"项目":"完整-中","数值":int((df["数据完整度"]=="中").sum())},
                 {"项目":"完整-低","数值":int((df["数据完整度"]=="低").sum())}]
        pd.DataFrame(stats).to_excel(w, sheet_name='统计概览', index=False)
    return path

