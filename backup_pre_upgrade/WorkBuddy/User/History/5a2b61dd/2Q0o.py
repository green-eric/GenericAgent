def fetch_stock_finance(ts_code, name):
    query = f"{ts_code} {name} 年报 主要财务指标 利润表 现金流量表 资产负债表"
    result = run_neodata(query)
    base = {"ts_code":ts_code,"name":name,"industry_l1_parsed":None,"fetch_success":False}
    if result.get("code")!="200":
        error_log.append({"股票代码":ts_code,"股票名称":name,"阶段":"财务数据获取","错误详情":f"API错误码 {result.get('code')}"})
        return base
    recalls = result.get("data",{}).get("apiData",{}).get("apiRecall",[])
    all_content = "\n".join(r.get("content","") for r in recalls)
    if not all_content:
        error_log.append({"股票代码":ts_code,"股票名称":name,"阶段":"财务数据获取","错误详情":"API返回空文本"})
        return base
    base["fetch_success"]=True
    try: base.update(parse_financial_all(all_content))
    except Exception as e:
        error_log.append({"股票代码":ts_code,"股票名称":name,"阶段":"财务指标解析","错误详情":str(e)})
    ind = extract_industry_from_content(all_content)
    if ind: base["industry_l1_parsed"] = ind
    return base

def fetch_stock_batch(stocks, workers):
    results, empty_streak, failed = [],0,0
    print(f"[批次] {len(stocks)}只, {workers}线程")
    with ThreadPoolExecutor(max_workers=workers) as ex:
        fut = {ex.submit(fetch_stock_finance,s["ts_code"],s["name"]):s for s in stocks}
        for f in as_completed(fut):
            s = fut[f]
            try:
                r = f.result(); results.append(r)
                if not any(r.get(k) for k in ["annual_roe","annual_gross_margin","annual_debt_ratio"]):
                    empty_streak+=1; failed+=1
                else: empty_streak=0
            except Exception as e:
                print(f"异常 {s['ts_code']}: {e}")
                error_log.append({"股票代码":s["ts_code"],"股票名称":s["name"],"阶段":"并发获取","错误详情":str(e)})
                results.append({"ts_code":s["ts_code"],"name":s["name"],"error":str(e)})
                empty_streak+=1; failed+=1
            if empty_streak>=Config.PAUSE_CONSECUTIVE_EMPTY:
                print(f"暂停{Config.PAUSE_DURATION}s"); time.sleep(Config.PAUSE_DURATION); empty_streak=0
    print(f"批次完成，失败/空: {failed}")
    return results

